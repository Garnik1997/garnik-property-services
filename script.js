/* =========================================================
   CHANGE LANGUAGE
========================================================= */

function changeLanguage(lang){

    if(!translations[lang]){
        lang = "en";
    }

    localStorage.setItem("language", lang);

    document.documentElement.lang = lang;

    const elements = document.querySelectorAll("[data-i18n]");

    elements.forEach(element => {

        const key = element.getAttribute("data-i18n");

        if(translations[lang][key] !== undefined){

            element.innerHTML = translations[lang][key];

        }

    });


    const placeholders =
    document.querySelectorAll("[data-i18n-placeholder]");

    placeholders.forEach(element => {

        const key =
        element.getAttribute("data-i18n-placeholder");

        if(translations[lang][key] !== undefined){

            element.placeholder =
            translations[lang][key];

        }

    });


    /* ACTIVE LANGUAGE */

    document.querySelectorAll(".language button")
    .forEach(button => {

        button.classList.remove("active");

    });


    const activeButton =
    document.querySelector(
        `.language button[onclick="changeLanguage('${lang}')"]`
    );

    if(activeButton){

        activeButton.classList.add("active");

    }


    /* UPDATE PAGE TITLE */

    const titles = {

        ru:
        "GARNIK PROPERTY SERVICES | Премиальное строительство в Барселоне",

        es:
        "GARNIK PROPERTY SERVICES | Construcción Premium en Barcelona",

        en:
        "GARNIK PROPERTY SERVICES | Premium Construction Barcelona"

    };

    document.title = titles[lang];

}


/* =========================================================
   PAGE LOAD
========================================================= */

document.addEventListener("DOMContentLoaded", () => {


    /* LANGUAGE */

    const savedLanguage =
    localStorage.getItem("language") || "en";

    changeLanguage(savedLanguage);


    /* =====================================================
       SCROLL ANIMATION
    ===================================================== */

    const sections =
    document.querySelectorAll("section");


    const observer =
    new IntersectionObserver(

        (entries) => {

            entries.forEach(entry => {

                if(entry.isIntersecting){

                    entry.target.classList.add("show");

                    observer.unobserve(entry.target);

                }

            });

        },

        {
            threshold:0.12
        }

    );


    sections.forEach(section => {

        section.classList.add("hidden");

        observer.observe(section);

    });


    /* =====================================================
       SMOOTH SCROLL
    ===================================================== */

    document.querySelectorAll('a[href^="#"]')
    .forEach(anchor => {

        anchor.addEventListener("click", function(e){

            const target =
            document.querySelector(
                this.getAttribute("href")
            );

            if(target){

                e.preventDefault();

                target.scrollIntoView({
                    behavior:"smooth",
                    block:"start"
                });

            }

        });

    });


    /* =====================================================
       NAVBAR SCROLL
    ===================================================== */

    const navbar =
    document.querySelector(".navbar");


    window.addEventListener("scroll", () => {

        if(!navbar){
            return;
        }

        if(window.scrollY > 80){

            navbar.style.padding = "14px 0";

            navbar.style.background =
            "rgba(5,5,7,.94)";

        }else{

            navbar.style.padding = "25px 0";

            navbar.style.background =
            "rgba(7,8,10,.72)";

        }

    });


    /* =====================================================
       CONTACT FORM
    ===================================================== */

    const form =
    document.querySelector(".contact-form");


    if(form){

        form.addEventListener("submit", function(e){

            e.preventDefault();

            const currentLanguage =
            localStorage.getItem("language") || "en";


            const messages = {

                ru:
                "Спасибо! Ваша заявка отправлена. Мы свяжемся с вами в ближайшее время.",

                es:
                "¡Gracias! Su solicitud ha sido enviada. Nos pondremos en contacto con usted pronto.",

                en:
                "Thank you! Your request has been sent. We will contact you shortly."

            };


            alert(messages[currentLanguage]);

            form.reset();

        });

    }


});
